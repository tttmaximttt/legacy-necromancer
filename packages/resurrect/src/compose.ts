import type { BuildRecipe, DetectedService, SandboxLimits } from '@necromancer/core';
import { stringify } from 'yaml';
import { serviceEnv } from './detect.js';

export const DEFAULT_LIMITS: SandboxLimits = { cpus: 2, memoryMb: 2048, pids: 512, stepTimeoutSec: 900 };

/** Per-service limits: services are smaller than the app. */
export function serviceLimits(limits: SandboxLimits): Pick<SandboxLimits, 'cpus' | 'memoryMb' | 'pids'> {
  return { cpus: Math.max(0.5, limits.cpus / 2), memoryMb: Math.max(256, Math.floor(limits.memoryMb / 2)), pids: limits.pids };
}

/**
 * A compose file for running the revived app yourself, with the same sandbox the loop uses: no network beyond
 * the app's own localhost (services join the app's network namespace), no host mounts, no capabilities for the
 * app, no privilege escalation, and CPU, memory and process limits on every container.
 */
export function renderCompose(recipe: BuildRecipe, services: DetectedService[], limits: SandboxLimits): string {
  const hardening = (l: Pick<SandboxLimits, 'cpus' | 'memoryMb' | 'pids'>) => ({
    cpus: l.cpus,
    mem_limit: `${l.memoryMb}m`,
    pids_limit: l.pids,
    security_opt: ['no-new-privileges:true'],
  });
  const app: Record<string, unknown> = {
    build: { context: '.', dockerfile: 'Dockerfile.necromancer' },
    image: 'necromancer/app',
    environment: recipe.env,
    ...hardening(limits),
    // Database images switch users at start-up, so only the app drops every capability.
    cap_drop: ['ALL'],
    // The app may start before its database is ready; old apps tend to crash rather than retry.
    restart: 'on-failure',
    // No network at runtime: dependencies were installed at build time.
    network_mode: 'none',
  };
  const doc: { name: string; services: Record<string, unknown> } = { name: 'necromancer', services: { app } };
  if (services.length) {
    // The app owns the network namespace; services join it so "localhost:27017" in old code still works.
    for (const s of services) {
      doc.services[s.kind] = {
        image: s.image,
        ...(Object.keys(serviceEnv(s.kind)).length && { environment: serviceEnv(s.kind) }),
        network_mode: 'service:app',
        ...hardening(serviceLimits(limits)),
      };
    }
  }
  if (recipe.buildCommand) app.command = ['sh', '-c', `${recipe.buildCommand} && ${recipe.startCommand ?? 'node .'}`];
  return `# Generated by necromancer resurrect. Run: docker compose -f docker-compose.necromancer.yml up --build\n${stringify(doc, { aliasDuplicateObjects: false })}`;
}
